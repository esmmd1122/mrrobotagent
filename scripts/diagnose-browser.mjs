import { chromium } from 'playwright'
import { PrismaClient } from '@prisma/client'

const prisma = new PrismaClient()
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
const slug = `diag${Date.now()}`.slice(0, 18)
page.on('console', (message) => console.log('console', message.type(), message.text()))
page.on('response', async (response) => {
  if (response.request().method() !== 'POST') return
  const body = await response.text().catch(() => '')
  console.log('POST', response.status(), response.url(), body.slice(0, 300).replace(/\s+/g, ' '))
})

await page.goto('http://localhost:3122/studio/register', { waitUntil: 'domcontentloaded' })
await page.getByPlaceholder('نام سالن').fill('تشخیص')
await page.getByPlaceholder('شناسه انگلیسی مثل liana-salon').fill(slug)
await page.getByPlaceholder('نام شما').fill('مالک')
await page.getByPlaceholder('ایمیل').fill(`${slug}@example.com`)
await page.getByPlaceholder('رمز عبور').fill('password123')
await page.getByRole('button', { name: 'ادامه راه‌اندازی' }).click()
await page.getByRole('heading', { name: 'تشخیص' }).waitFor({ timeout: 30000 })

await page.goto('http://localhost:3122/studio/services', { waitUntil: 'domcontentloaded' })
await page.goto('http://localhost:3122/studio/team', { waitUntil: 'domcontentloaded' })
await page.getByPlaceholder('نام').fill('نیلوفر')
await page.getByRole('button', { name: 'افزودن' }).click()
await page.getByText('نیلوفر').waitFor({ timeout: 30000 })
await page.goto('http://localhost:3122/studio/services', { waitUntil: 'domcontentloaded' })
await page.getByPlaceholder('نام خدمت').fill('کوتاهی')
await page.getByPlaceholder('قیمت تومان').fill('250000')
await page.getByPlaceholder('مدت دقیقه').fill('30')
await page.getByLabel('نیلوفر').check()
await page.getByRole('button', { name: 'افزودن خدمت' }).click()
await page.waitForTimeout(8000)
const services = await prisma.salonOffering.findMany({ where: { business: { slug } }, include: { employees: true } })
console.log('services', services.map((item) => ({ name: item.name, staff: item.employees.length })))

await page.goto('http://localhost:3122/studio/settings', { waitUntil: 'domcontentloaded' })
await page.getByRole('button', { name: 'انتشار صفحه رزرو' }).click()
await page.waitForTimeout(5000)
await page.goto(`http://localhost:3122/salon/${slug}`, { waitUntil: 'domcontentloaded' })
await page.locator('input[type="date"]').fill('2026-11-15')
const slotsResponse = page.waitForResponse((response) => response.url().includes('/slots'))
await page.getByRole('button', { name: 'نمایش زمان‌ها' }).click()
console.log('slots', await (await slotsResponse).text())
await page.goto('http://localhost:3122/studio/schedule', { waitUntil: 'domcontentloaded' })
await page.locator('input[name="date"]').first().fill('2027-01-01')
await page.getByRole('button', { name: 'ثبت تعطیلی' }).click()
await page.waitForTimeout(8000)
const holidays = await prisma.salonHoliday.findMany({ where: { business: { slug } } })
console.log('holidays', holidays.map((item) => item.date))
await page.screenshot({ path: 'test-results/diagnose-holiday.png', fullPage: true })
await prisma.salonBusiness.deleteMany({ where: { slug } })
await browser.close()
await prisma.$disconnect()
